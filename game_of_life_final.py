def count_live_neighbors(real_world, row, col):
  count = 0
  for r in range(row - 1, row +2):
    for c in range(col -1, col + 2):
      if r == row and c == col:
        continue
      if in_bounds(real_world, r, c):
        count += real_world[r][c]
  return count

